import { createReadStream } from 'node:fs';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { Readable } from 'node:stream';
import { env } from '../config/env.js';

// Where file bytes are kept. Only the local disk provider exists today. A cloud provider (for example S3 or
// Azure Blob) can be added later by implementing the same three methods, without changing the routes.
export interface StorageProvider {
  put(key: string, data: Buffer): Promise<void>;
  open(key: string): Promise<Readable>;
  remove(key: string): Promise<void>;
}

class LocalDiskStorage implements StorageProvider {
  private readonly root: string;

  constructor(root: string) {
    this.root = path.resolve(root);
  }

  // Keys are generated by the server, but the path is still checked so it can never point outside the storage folder.
  private resolve(key: string): string {
    const full = path.resolve(this.root, key);
    if (!full.startsWith(this.root + path.sep)) throw new Error('Invalid storage key.');
    return full;
  }

  async put(key: string, data: Buffer): Promise<void> {
    const full = this.resolve(key);
    await mkdir(path.dirname(full), { recursive: true });
    // 'wx' refuses to overwrite an existing file, so a stored original can never be replaced.
    await writeFile(full, data, { flag: 'wx' });
  }

  async open(key: string): Promise<Readable> {
    const full = this.resolve(key);
    await stat(full);
    return createReadStream(full);
  }

  async remove(key: string): Promise<void> {
    await rm(this.resolve(key), { force: true });
  }
}

export const storage: StorageProvider = new LocalDiskStorage(env.STORAGE_DIR);
