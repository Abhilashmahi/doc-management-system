-- Phase 2: file storage, document and template details, default categories and fields, and application settings.
-- Statements that use columns added in this same file run as dynamic SQL, because SQL Server checks column names when a batch is compiled.

-- Every stored file (document uploads and designer images). The bytes live in the storage provider, not in the database.
IF OBJECT_ID(N'dbo.StoredFiles', N'U') IS NULL
CREATE TABLE dbo.StoredFiles (
  Id            INT IDENTITY(1,1) PRIMARY KEY,
  AccountId     INT NOT NULL REFERENCES dbo.Accounts(Id),
  Purpose       NVARCHAR(20) NOT NULL,                       -- document | asset
  StorageKey    NVARCHAR(400) NOT NULL,                      -- location inside the storage provider, generated by the server
  OriginalName  NVARCHAR(260) NOT NULL,
  MimeType      NVARCHAR(150) NOT NULL,
  SizeBytes     BIGINT NOT NULL,
  Sha256        CHAR(64) NOT NULL,
  CreatedById   INT NOT NULL REFERENCES dbo.Users(Id),
  CreatedAt     DATETIME2 NOT NULL CONSTRAINT DF_StoredFiles_CreatedAt DEFAULT SYSUTCDATETIME(),
  CONSTRAINT UQ_StoredFiles_StorageKey UNIQUE (StorageKey),
  CONSTRAINT CK_StoredFiles_Purpose CHECK (Purpose IN (N'document', N'asset'))
);
CREATE INDEX IX_StoredFiles_Account ON dbo.StoredFiles (AccountId) INCLUDE (SizeBytes);

-- Documents: the original upload, when it was last opened, and soft delete.
ALTER TABLE dbo.Documents ADD
  FileId        INT NULL CONSTRAINT FK_Documents_File REFERENCES dbo.StoredFiles(Id),
  LastOpenedAt  DATETIME2 NULL,
  DeletedAt     DATETIME2 NULL;
CREATE INDEX IX_Documents_Account_Updated ON dbo.Documents (AccountId, UpdatedAt DESC);

ALTER TABLE dbo.DocumentVersions ADD
  FileId  INT NULL CONSTRAINT FK_DocumentVersions_File REFERENCES dbo.StoredFiles(Id),
  Note    NVARCHAR(200) NULL;

-- Templates: a description, and per-version field settings (which fields are required, default values).
ALTER TABLE dbo.Templates ADD Description NVARCHAR(500) NULL;
ALTER TABLE dbo.TemplateVersions ADD FieldsJson NVARCHAR(MAX) NULL;

-- Field definitions: a default value. Options for "select" fields live in ValidationJson.
ALTER TABLE dbo.FieldDefinitions ADD DefaultValue NVARCHAR(500) NULL;

CREATE INDEX IX_AuditLogs_Action_Created ON dbo.AuditLogs (Action, CreatedAt) INCLUDE (AccountId);

-- Default application settings. Administrators change them on the Settings page.
INSERT INTO dbo.AppSettings ([Key], [Value])
SELECT v.[Key], v.[Value]
FROM (VALUES
  (N'app_name', N'e-Sevai Document Manager'),
  (N'brand_color', N'#4f46e5'),
  (N'allowed_file_types', N'pdf,docx,xlsx,csv,txt,png,jpg,jpeg'),
  (N'max_upload_mb', N'20'),
  (N'default_export_format', N'pdf'),
  (N'audit_retention_days', N'365')
) AS v([Key], [Value])
WHERE NOT EXISTS (SELECT 1 FROM dbo.AppSettings s WHERE s.[Key] = v.[Key]);

-- Give every existing office the starter categories and fields. New offices get them when they are created.
INSERT INTO dbo.DocumentCategories (AccountId, Name)
SELECT a.Id, c.Name
FROM dbo.Accounts a
CROSS JOIN (VALUES
  (N'Birth Certificate'), (N'Death Certificate'), (N'Community Certificate'), (N'Income Certificate'),
  (N'Residence Certificate'), (N'Nativity Certificate'), (N'Other Documents')
) AS c(Name)
WHERE NOT EXISTS (SELECT 1 FROM dbo.DocumentCategories d WHERE d.AccountId = a.Id AND d.Name = c.Name);

EXEC (N'
INSERT INTO dbo.FieldDefinitions (AccountId, FieldKey, Label, DataType, ValidationJson)
SELECT a.Id, f.FieldKey, f.Label, f.DataType, f.ValidationJson
FROM dbo.Accounts a
CROSS JOIN (VALUES
  (N''FullName'', N''Full Name'', N''text'', N''{"required":true,"maxLength":150}''),
  (N''Age'', N''Age'', N''number'', N''{"min":0,"max":150}''),
  (N''DateOfBirth'', N''Date of Birth'', N''date'', NULL),
  (N''Gender'', N''Gender'', N''select'', N''{"options":["Male","Female","Transgender"]}''),
  (N''ParentName'', N''Parent or Guardian Name'', N''text'', N''{"maxLength":150}''),
  (N''Address'', N''Address'', N''multiline'', N''{"maxLength":500}''),
  (N''CertificateNumber'', N''Certificate Number'', N''text'', N''{"maxLength":50}''),
  (N''RegistrationNumber'', N''Registration Number'', N''text'', N''{"maxLength":50}''),
  (N''IssueDate'', N''Issue Date'', N''date'', NULL)
) AS f(FieldKey, Label, DataType, ValidationJson)
WHERE NOT EXISTS (SELECT 1 FROM dbo.FieldDefinitions d WHERE d.AccountId = a.Id AND d.FieldKey = f.FieldKey);
');
